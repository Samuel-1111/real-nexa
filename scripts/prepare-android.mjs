import fs from 'node:fs';
import path from 'node:path';

const manifest = path.join(process.cwd(), 'android/app/src/main/AndroidManifest.xml');
if (!fs.existsSync(manifest)) throw new Error('AndroidManifest.xml was not generated by Capacitor.');
let xml = fs.readFileSync(manifest, 'utf8');

const permissions = [
  'android.permission.INTERNET',
  'android.permission.RECORD_AUDIO',
  'android.permission.CAMERA',
  'android.permission.POST_NOTIFICATIONS',
  'android.permission.SCHEDULE_EXACT_ALARM',
  'android.permission.WAKE_LOCK'
];
for (const permission of permissions) {
  if (!xml.includes('android:name="' + permission + '"')) {
    xml = xml.replace(/(<manifest[^>]*>)/, '$1\n    <uses-permission android:name="' + permission + '" />');
  }
}

const icon = path.join(process.cwd(), 'android/app/src/main/res/drawable/ic_nexa.xml');
if (fs.existsSync(icon)) {
  xml = xml.replace(/android:icon="@mipmap\/ic_launcher"/, 'android:icon="@drawable/ic_nexa"');
  xml = xml.replace(/android:roundIcon="@mipmap\/ic_launcher_round"/, 'android:roundIcon="@drawable/ic_nexa"');
}
if (!xml.includes('android:name=".ReminderAlarmReceiver"')) {
  xml = xml.replace('</application>', '    <receiver android:name=".ReminderAlarmReceiver" android:exported="false" />\n    </application>');
}
fs.writeFileSync(manifest, xml);

for (const gradleName of ['build.gradle.kts', 'build.gradle']) {
  const gradle = path.join(process.cwd(), 'android/app', gradleName);
  if (!fs.existsSync(gradle)) continue;
  let g = fs.readFileSync(gradle, 'utf8');
  const deps = gradleName.endsWith('.kts')
    ? ['implementation("androidx.core:core-ktx:1.17.0")', 'implementation("androidx.webkit:webkit:1.14.0")']
    : ["implementation 'androidx.core:core-ktx:1.17.0'", "implementation 'androidx.webkit:webkit:1.14.0'"];
  for (const dep of deps) {
    if (!g.includes(dep)) {
      if (!g.includes('dependencies {')) throw new Error('Could not find dependencies block in ' + gradleName);
      g = g.replace('dependencies {', 'dependencies {\n    ' + dep);
    }
  }
  fs.writeFileSync(gradle, g);
  break;
}
